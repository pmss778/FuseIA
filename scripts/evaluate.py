#!/usr/bin/env python3
"""Serial actual-query evaluation for one or more FuseIA recommendation JSON files."""
from __future__ import annotations

import argparse
import json
import re
import time
import uuid
from pathlib import Path


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", required=True)
    parser.add_argument("--workload", type=Path, required=True)
    parser.add_argument("--recommendation", type=Path, action="append", required=True,
                        help="Recommendation JSON; repeat to compare plans")
    parser.add_argument("--runs", type=int, default=3)
    parser.add_argument("--statement-timeout-seconds", type=int, default=600,
                        help="Set 0 to disable statement_timeout")
    parser.add_argument("--namespace", default=None,
                        help="Index namespace; a unique namespace is generated by default")
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args()


def indexes_from(path):
    data = json.loads(path.read_text(encoding="utf-8"))
    indexes = data.get("indexes")
    if indexes is None:
        indexes = data.get("final_indexes")
    if indexes is None and isinstance(data.get("rollout"), dict):
        indexes = data["rollout"].get("final_indexes")
    if not isinstance(indexes, list):
        raise ValueError(f"No index list found in {path}")
    normalized = list(dict.fromkeys(str(x) for x in indexes))
    if len(normalized) != len(indexes):
        raise ValueError(f"Duplicate indexes in recommendation: {path}")
    safe = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\([A-Za-z_][A-Za-z0-9_]*(?:\s*,\s*[A-Za-z_][A-Za-z0-9_]*)*\)")
    invalid = [name for name in normalized if not safe.fullmatch(name)]
    if invalid:
        raise ValueError(f"Invalid index identifier(s) in {path}: {invalid}")
    return normalized, data


def reconcile(runner, indexes):
    conn, cursor = runner._connect()
    runner._conn = conn
    try:
        runner._reconcile(cursor, indexes)
    finally:
        del runner._conn
        cursor.close()
        conn.close()


def save(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                         encoding="utf-8")
    temporary.replace(path)


def main():
    args = parse_args()
    if args.output.exists():
        raise FileExistsError(f"Refusing to overwrite {args.output}")
    if not args.workload.is_file():
        raise FileNotFoundError(args.workload)
    if args.runs < 1 or args.statement_timeout_seconds < 0:
        raise ValueError("runs must be positive and statement timeout non-negative")
    namespace = args.namespace or f"fuseia_eval_{uuid.uuid4().hex[:8]}"
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]{0,30}", namespace):
        raise ValueError("namespace must be a short SQL-safe identifier")

    from grpo_reward import WorkloadRunner
    from recommendation_rollout import load_queries

    queries = load_queries(args.workload)
    if not queries:
        raise ValueError("workload contains no queries")
    result = {
        "status": "running", "database": args.database,
        "workload": str(args.workload), "query_count": len(queries),
        "runs_per_query": args.runs, "namespace": namespace,
        "statement_timeout_seconds": args.statement_timeout_seconds,
        "timing": "actual SQL execution plus full fetch; per-query medians summed",
        "configurations": [],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    save(args.output, result)
    runner = WorkloadRunner(args.database, queries, namespace=namespace,
                            statement_timeout_s=args.statement_timeout_seconds)
    owns_namespace = False
    try:
        for position, path in enumerate(args.recommendation, start=1):
            indexes, source = indexes_from(path)
            configuration = {"label": path.stem, "source": str(path),
                             "indexes": indexes, "status": "preflight"}
            result["configurations"].append(configuration)
            save(args.output, result)
            conn, cursor = runner._connect()
            runner._conn = conn
            try:
                preexisting = runner._physical_indexes(cursor)
                if preexisting:
                    raise RuntimeError(
                        f"Evaluation namespace {namespace!r} is not clean: "
                        f"{sorted(preexisting)}")
                owns_namespace = True
                cursor.execute(
                    "SELECT pid, application_name, state FROM pg_stat_activity "
                    "WHERE datname=current_database() AND state='active' "
                    "AND pid<>pg_backend_pid() AND backend_type='client backend'")
                concurrent = cursor.fetchall()
                if concurrent:
                    raise RuntimeError(f"Database has active client queries: {concurrent}")
                configuration["base_indexes_untouched"] = runner.base_index_snapshot(cursor)
                runner._reconcile(cursor, indexes)
                cursor.execute(
                    "SELECT i.relname, pg_relation_size(i.oid) "
                    "FROM pg_index x JOIN pg_class i ON i.oid=x.indexrelid "
                    "JOIN pg_namespace n ON n.oid=i.relnamespace "
                    "WHERE n.nspname='public' AND i.relname LIKE %s "
                    "ORDER BY i.relname",
                    (f"ix_{namespace}_%",))
                actual = [{"name": name, "bytes": int(size)}
                          for name, size in cursor.fetchall()]
                if len(actual) != len(indexes):
                    raise RuntimeError("One or more recommended indexes could not be created")
                actual_mib = round(sum(x["bytes"] for x in actual) / (1024 ** 2), 3)
                configuration["actual_indexes"] = actual
                configuration["actual_index_storage_mib"] = actual_mib
            finally:
                del runner._conn
                cursor.close()
                conn.close()

            budget = source.get("budget_mib")
            configuration["budget_mib"] = budget
            if budget is not None and actual_mib > float(budget):
                configuration.update(status="skipped_over_budget")
                reconcile(runner, [])
                save(args.output, result)
                print(f"[{position}/{len(args.recommendation)}] {path.stem}: "
                      "skipped; actual indexes exceed budget", flush=True)
                continue

            measured = runner.measure(indexes, runs=args.runs)
            configuration.update(
                status="completed" if not measured["failures"] else "completed_with_failures",
                median_query_seconds=measured["seconds"],
                workload_total_seconds=measured["total"],
                failures=measured["failures"],
                executed_queries=measured["executed_queries"],
                cached_queries=measured["cached_queries"],
                timing_retries=measured["retries"],
                low_confidence=measured["low_confidence"],
            )
            reconcile(runner, [])
            save(args.output, result)
            print(f"[{position}/{len(args.recommendation)}] {path.stem}: "
                  f"{configuration['workload_total_seconds']} s", flush=True)
        result["status"] = "completed"
    except Exception as exc:
        result["status"] = "failed"
        result["error"] = f"{type(exc).__name__}: {exc}"
        raise
    finally:
        if owns_namespace:
            try:
                reconcile(runner, [])
            except Exception as cleanup_error:
                result["cleanup_error"] = f"{type(cleanup_error).__name__}: {cleanup_error}"
        result["finished_epoch"] = time.time()
        save(args.output, result)


if __name__ == "__main__":
    main()
